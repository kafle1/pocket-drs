#!/usr/bin/env python
"""Every number quoted in the manuscript, as a LaTeX macro from the raw result files.

Usage:  python make_numbers.py   (writes ../numbers.tex and ../tables/*.tex)
"""
import csv
import json
import os
import statistics

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(HERE, "raw")
PAPER = os.path.dirname(HERE)
TABLES = os.path.join(PAPER, "tables")
os.makedirs(TABLES, exist_ok=True)


def rows(name):
    out = []
    with open(os.path.join(RAW, name), newline="") as fh:
        for r in csv.DictReader(fh):
            d = {}
            for k, v in r.items():
                if v in ("", None):
                    d[k] = None
                elif v in ("True", "False"):
                    d[k] = v == "True"
                else:
                    try:
                        d[k] = float(v) if ("." in v or "e" in v.lower() or "nan" in v.lower()) else int(v)
                    except ValueError:
                        d[k] = v
            out.append(d)
    return out


macros = {}


_DIGITS = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}


def m(name, value, fmt="{:.1f}"):
    # LaTeX macro names cannot contain digits
    name = "".join(_DIGITS.get(ch, ch) for ch in name)
    macros[name] = fmt.format(value) if not isinstance(value, str) else value


def med(xs):
    xs = [x for x in xs if x is not None and not (isinstance(x, float) and np.isnan(x))]
    return float(np.median(xs)) if xs else float("nan")


def p90(xs):
    xs = [x for x in xs if x is not None and not (isinstance(x, float) and np.isnan(x))]
    return float(np.percentile(xs, 90)) if xs else float("nan")


def agree(rs, key="verdict"):
    return 100.0 * sum(1 for r in rs if r[key] == r["truth"]) / max(1, len(rs))


def false_out(rs, key="verdict"):
    return sum(1 for r in rs if r[key] == "out" and r["truth"] == "not_out")


def missed_out(rs, key="verdict"):
    return sum(1 for r in rs if r[key] == "not_out" and r["truth"] == "out")


def ump(rs, key="verdict"):
    return sum(1 for r in rs if r[key] == "umpires_call")


def write_table(name, lines):
    with open(os.path.join(TABLES, name), "w") as fh:
        fh.write("% generated by experiments/make_numbers.py; do not edit\n" + "\n".join(lines) + "\n")


